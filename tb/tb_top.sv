module tb_top;

    // ============================================================
    // Import UVM and project package
    // ============================================================

    import uvm_pkg::*;
    import fp32_pkg::*;


    // ============================================================
    // Interface
    // ============================================================

    fp32_if intf();


    // ============================================================
    // DUT
    // ============================================================

    fp32_classifier dut (
        .fp32       (intf.fp32),
        .class_type (intf.class_type)
    );


    // ============================================================
    // Assertions
    // ============================================================

    fp32_classifier_sva sva (
        .vif (intf)
    );


    // ============================================================
    // Start UVM
    // ============================================================

    initial begin

        // Pass the real interface to UVM components
        uvm_config_db #(virtual fp32_if)::set(
            null,
            "*",
            "vif",
            intf
        );

        // Start the UVM test
        run_test("fp32_test");

    end

endmodule
